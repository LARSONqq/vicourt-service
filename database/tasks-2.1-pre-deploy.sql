create or replace function public.complete_manual_recurring_task(
  p_task_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  task_row public.object_tasks%rowtype;
  completed_row public.object_tasks%rowtype;
  next_task_row public.object_tasks%rowtype;
  template_row public.task_templates%rowtype;
  next_slot record;
  today date := (clock_timestamp() at time zone 'Europe/Kyiv')::date;
begin
  if auth.uid() is null or not private.is_active_user() then
    raise exception 'Only an active authenticated user can complete a task.'
      using errcode = '42501';
  end if;

  select task.*
  into task_row
  from public.object_tasks task
  where task.id = p_task_id;

  if not found then
    raise exception 'Task was not found.'
      using errcode = 'P0002';
  end if;

  if task_row.task_source <> 'manual'
    or task_row.task_template_id is null
    or task_row.recurrence_sequence is null
  then
    raise exception 'Task is not a manual recurring occurrence.'
      using errcode = '22023';
  end if;

  select template.*
  into template_row
  from public.task_templates template
  where template.id = task_row.task_template_id
  for update;

  if not found then
    raise exception 'Recurring task template was not found.'
      using errcode = 'P0002';
  end if;

  -- All series mutations lock template -> occurrence in the same order. This
  -- prevents a deadlock with concurrent template update/disable operations.
  select task.*
  into task_row
  from public.object_tasks task
  where task.id = p_task_id
  for update;

  if not found
    or task_row.task_source <> 'manual'
    or task_row.task_template_id is distinct from template_row.id
    or task_row.recurrence_sequence is null
  then
    raise exception 'Recurring task occurrence changed or no longer exists.'
      using errcode = '40001';
  end if;

  if task_row.status = 'Виконано' then
    select task.*
    into next_task_row
    from public.object_tasks task
    where task.task_template_id = task_row.task_template_id
      and task.recurrence_sequence > task_row.recurrence_sequence
      and task.status <> 'Виконано'
    order by task.recurrence_sequence, task.id
    limit 1;

    return jsonb_build_object(
      'already_completed', true,
      'template_id', template_row.id,
      'completed_task', to_jsonb(task_row),
      'next_task', case when next_task_row.id is null then null else to_jsonb(next_task_row) end
    );
  end if;

  if task_row.status not in ('Заплановано', 'В роботі') then
    raise exception 'Task is not in an active status.'
      using errcode = '22023';
  end if;

  perform pg_catalog.set_config(
    'vicourt.recurring_task_mutation',
    'on',
    true
  );

  update public.object_tasks
  set status = 'Виконано'
  where id = task_row.id
  returning * into completed_row;

  if template_row.is_active then
    select *
    into next_slot
    from private.next_task_recurrence_slot(
      template_row.anchor_due_date,
      template_row.recurrence_type,
      template_row.recurrence_interval,
      completed_row.recurrence_sequence,
      today
    );

    next_task_row := private.create_task_template_occurrence(
      template_row.id,
      next_slot.recurrence_sequence,
      next_slot.due_date
    );
  end if;

  return jsonb_build_object(
    'already_completed', false,
    'template_id', template_row.id,
    'completed_task', to_jsonb(completed_row),
    'next_task', case when next_task_row.id is null then null else to_jsonb(next_task_row) end
  );
end
$function$;

