create or replace function public.create_equipment_service_record_v2(
  p_equipment_id bigint,
  p_service_type text,
  p_service_date date,
  p_cost numeric,
  p_performed_by text,
  p_description text,
  p_next_service_date date,
  p_usage_reading numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  equipment_row public.equipment%rowtype;
  actor_name text;
  usage_result jsonb;
  usage_log_id bigint;
  service_history_id bigint;
  task_result jsonb;
begin
  if auth.uid() is null
    or not private.is_active_user()
    or not private.is_admin()
  then
    raise exception 'Only an active administrator can create equipment service records.'
      using errcode = '42501';
  end if;

  if p_service_type not in (
    'Планове обслуговування',
    'Ремонт',
    'Заміна запчастин',
    'Діагностика',
    'Інше'
  ) then
    raise exception 'Unsupported equipment service type.'
      using errcode = '22023';
  end if;

  if p_service_type = 'Планове обслуговування' then
    raise exception 'Use the canonical maintenance completion function for planned maintenance.'
      using errcode = '22023';
  end if;

  if p_service_date is null
    or p_service_date > (clock_timestamp() at time zone 'Europe/Kyiv')::date
  then
    raise exception 'Service date is invalid or in the future.'
      using errcode = '22007';
  end if;

  if p_next_service_date is not null and p_next_service_date < p_service_date then
    raise exception 'Next service date cannot be before the service date.'
      using errcode = '22007';
  end if;

  if p_cost is null
    or p_cost < 0
    or p_cost = 'NaN'::numeric
    or p_cost >= 'Infinity'::numeric
  then
    raise exception 'Service cost must be a finite non-negative number.'
      using errcode = '22023';
  end if;

  if p_performed_by is not null and char_length(p_performed_by) > 300 then
    raise exception 'Service performer is too long.'
      using errcode = '22001';
  end if;

