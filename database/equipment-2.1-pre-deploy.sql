-- The same active task is used for date and usage criteria. A future date is
-- not fabricated for usage-only maintenance.
create or replace function public.sync_equipment_maintenance_task(
  p_equipment_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  equipment_row public.equipment%rowtype;
  task_row public.object_tasks%rowtype;
  today date := (clock_timestamp() at time zone 'Europe/Kyiv')::date;
  usage_due boolean := false;
  usage_schedule_active boolean := false;
  desired_due_date date;
  desired_title text;
  desired_description text;
begin
  if auth.uid() is null
    or not private.is_active_user()
    or not private.is_admin()
  then
    raise exception 'Only an active administrator can manage equipment maintenance.'
      using errcode = '42501';
  end if;

  select equipment.*
  into equipment_row
  from public.equipment equipment
  where equipment.id = p_equipment_id
  for update;

  if not found then
    raise exception 'Equipment was not found.'
      using errcode = 'P0002';
  end if;

  usage_schedule_active :=
    equipment_row.usage_type in ('hours', 'km')
    and equipment_row.maintenance_interval_usage is not null
    and equipment_row.next_maintenance_usage is not null
    and equipment_row.maintenance_interval_usage > 0;
  usage_due :=
    usage_schedule_active
    and equipment_row.current_usage is not null
    and equipment_row.current_usage >= equipment_row.next_maintenance_usage;

  desired_due_date := equipment_row.next_service_date;

  if usage_due
    and (
      desired_due_date is null
      or today < desired_due_date
    )
  then
    desired_due_date := today;
  end if;

  desired_title := 'Планове ТО: ' || equipment_row.name;
  desired_description :=
    case
      when usage_schedule_active and equipment_row.next_service_date is not null
        then 'Планове ТО за датою або напрацюванням — залежно від того, який критерій настане раніше.'
      when usage_schedule_active
        then 'Планове ТО за напрацюванням.'
      else 'Планове ТО за датою.'
    end;

  select tasks.*
  into task_row
  from public.object_tasks tasks
  where tasks.equipment_id = equipment_row.id
    and tasks.task_source = 'equipment_maintenance'
    and tasks.status <> 'Виконано'
  order by tasks.id
  limit 1
  for update;

  if desired_due_date is null then
    if task_row.id is null then
      return jsonb_build_object('action', 'none', 'task_id', null);
    end if;

    delete from public.object_tasks tasks
    where tasks.equipment_id = equipment_row.id
      and tasks.task_source = 'equipment_maintenance'
      and tasks.status <> 'Виконано';

    return jsonb_build_object('action', 'removed', 'task_id', task_row.id);
  end if;

  if task_row.id is null then
    insert into public.object_tasks (
      object_id,
      equipment_id,
      title,
      description,
      due_date,
      assignee,
      assigned_employee_id,
      priority,
      status,
      task_source
    )
    values (
      null,
      equipment_row.id,
      desired_title,
      desired_description,
      desired_due_date,
      equipment_row.responsible,
      equipment_row.responsible_employee_id,
      'Високий',
      'Заплановано',
      'equipment_maintenance'
    )
    returning * into task_row;

    return jsonb_build_object('action', 'created', 'task_id', task_row.id);
  end if;

  if task_row.title is not distinct from desired_title
    and task_row.description is not distinct from desired_description
    and task_row.due_date is not distinct from desired_due_date
    and task_row.assignee is not distinct from equipment_row.responsible
    and task_row.assigned_employee_id is not distinct from equipment_row.responsible_employee_id
  then
    return jsonb_build_object('action', 'none', 'task_id', task_row.id);
  end if;

  update public.object_tasks
  set
    title = desired_title,
    description = desired_description,
    due_date = desired_due_date,
    assignee = equipment_row.responsible,
    assigned_employee_id = equipment_row.responsible_employee_id
  where id = task_row.id;

  return jsonb_build_object('action', 'updated', 'task_id', task_row.id);
end
$function$;

create or replace function public.configure_equipment_usage_schedule(
  p_equipment_id bigint,
  p_usage_type text,
  p_maintenance_interval_usage numeric,
  p_next_maintenance_usage numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  equipment_row public.equipment%rowtype;
  latest_usage_type text;
  next_usage numeric(18,3);
  task_result jsonb;
begin
  if auth.uid() is null
    or not private.is_active_user()
    or not private.is_admin()
  then
    raise exception 'Only an active administrator can configure equipment usage.'
      using errcode = '42501';
  end if;

  if p_usage_type not in ('none', 'hours', 'km') then
    raise exception 'Unsupported equipment usage type.'
      using errcode = '22023';
  end if;

  if p_maintenance_interval_usage is not null
    and (
      p_maintenance_interval_usage <= 0
      or p_maintenance_interval_usage = 'NaN'::numeric
      or p_maintenance_interval_usage >= 'Infinity'::numeric
    )
  then
    raise exception 'Usage maintenance interval must be finite and greater than zero.'
      using errcode = '22023';
  end if;

  if p_next_maintenance_usage is not null
    and (
      p_next_maintenance_usage < 0
      or p_next_maintenance_usage = 'NaN'::numeric
      or p_next_maintenance_usage >= 'Infinity'::numeric
    )
  then
    raise exception 'Next maintenance usage must be finite and non-negative.'
      using errcode = '22023';
  end if;

  select equipment.*
  into equipment_row
  from public.equipment equipment
  where equipment.id = p_equipment_id
  for update;

  if not found then
    raise exception 'Equipment was not found.'
      using errcode = 'P0002';
  end if;

  select logs.usage_type
  into latest_usage_type
  from public.equipment_usage_logs logs
  where logs.equipment_id = equipment_row.id
  order by logs.reading_date desc, logs.id desc
  limit 1;

  if p_usage_type in ('hours', 'km')
    and latest_usage_type is not null
    and latest_usage_type <> p_usage_type
  then
    raise exception 'Existing usage history uses a different measurement type.'
      using errcode = '22023';
  end if;

  if p_usage_type = 'none' then
    update public.equipment
    set
      usage_type = 'none',
      maintenance_interval_usage = null,
      last_maintenance_usage = null,
      next_maintenance_usage = null
    where id = equipment_row.id;
  else
    if p_maintenance_interval_usage is null
      and p_next_maintenance_usage is not null
    then
      raise exception 'A next usage threshold requires a maintenance interval.'
        using errcode = '22023';
    end if;

    next_usage := p_next_maintenance_usage;

    if p_maintenance_interval_usage is not null and next_usage is null then
      if equipment_row.current_usage is null then
        raise exception 'Record the current usage before enabling usage maintenance.'
          using errcode = '22023';
      end if;

      next_usage := equipment_row.current_usage + p_maintenance_interval_usage;
    end if;

    update public.equipment
    set
      usage_type = p_usage_type,
      maintenance_interval_usage = p_maintenance_interval_usage,
      next_maintenance_usage = next_usage,
      last_maintenance_usage = case
        when p_maintenance_interval_usage is null then null
        else last_maintenance_usage
      end
    where id = equipment_row.id;
  end if;

  task_result := public.sync_equipment_maintenance_task(equipment_row.id);

  return jsonb_build_object(
    'equipment_id', equipment_row.id,
    'equipment_name', equipment_row.name,
    'previous_usage_type', equipment_row.usage_type,
    'new_usage_type', p_usage_type,
    'previous_maintenance_interval_usage', equipment_row.maintenance_interval_usage,
    'new_maintenance_interval_usage', case when p_usage_type = 'none' then null else p_maintenance_interval_usage end,
    'previous_next_maintenance_usage', equipment_row.next_maintenance_usage,
    'new_next_maintenance_usage', case when p_usage_type = 'none' then null else next_usage end,
    'task_sync', task_result
  );
end
$function$;

create or replace function public.record_equipment_usage(
  p_equipment_id bigint,
  p_reading numeric,
  p_reading_date date,
  p_entry_type text,
  p_note text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  actor_name text;
  usage_result jsonb;
  task_result jsonb;
begin
  if auth.uid() is null
    or not private.is_active_user()
    or not private.is_admin()
  then
    raise exception 'Only an active administrator can record equipment usage.'
      using errcode = '42501';
  end if;

  select coalesce(
    nullif(btrim(profile.full_name), ''),
    nullif(btrim(profile.email), ''),
    'Користувач ViCourt'
  )
  into actor_name
  from public.profiles profile
  where profile.id = auth.uid();

  actor_name := coalesce(actor_name, 'Користувач ViCourt');

  usage_result := private.append_equipment_usage_log(
    p_equipment_id,
    p_reading,
    p_reading_date,
    p_entry_type,
    p_note,
    auth.uid(),
    actor_name,
    false
  );
  task_result := public.sync_equipment_maintenance_task(p_equipment_id);

  return usage_result || jsonb_build_object('task_sync', task_result);
end
$function$;

-- Fixed-arity canonical completion implementation. It owns all date/usage,
-- history and task changes in one database transaction.
create or replace function public.complete_equipment_maintenance_v2(
  p_equipment_id bigint,
  p_task_id bigint,
  p_cost numeric,
  p_performed_by text,
  p_description text,
  p_usage_reading numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  equipment_row public.equipment%rowtype;
  actor_name text;
  today date := (clock_timestamp() at time zone 'Europe/Kyiv')::date;
  has_date_schedule boolean;
  has_usage_schedule boolean;
  old_last_date date;
  old_next_date date;
  old_current_usage numeric(18,3);
  old_last_usage numeric(18,3);
  old_next_usage numeric(18,3);
  new_last_date date;
  new_next_date date;
  new_last_usage numeric(18,3);
  new_next_usage numeric(18,3);
  usage_result jsonb;
  usage_log_id bigint;
  service_history_id bigint;
  completed_task_id bigint;
  task_result jsonb;
  next_task_id bigint;
begin
  if auth.uid() is null
    or not private.is_active_user()
    or not private.is_admin()
  then
    raise exception 'Only an active administrator can complete equipment maintenance.'
      using errcode = '42501';
  end if;

  if p_cost is null
    or p_cost < 0
    or p_cost = 'NaN'::numeric
    or p_cost >= 'Infinity'::numeric
  then
    raise exception 'Maintenance cost must be a finite non-negative number.'
      using errcode = '22023';
  end if;

  if p_performed_by is not null and char_length(p_performed_by) > 300 then
    raise exception 'Maintenance performer is too long.'
      using errcode = '22001';
  end if;

  if p_description is not null and char_length(p_description) > 4000 then
    raise exception 'Maintenance description is too long.'
      using errcode = '22001';
  end if;

  select equipment.*
  into equipment_row
  from public.equipment equipment
  where equipment.id = p_equipment_id
  for update;

  if not found then
    raise exception 'Equipment was not found.'
      using errcode = 'P0002';
  end if;

  select coalesce(
    nullif(btrim(profile.full_name), ''),
    nullif(btrim(profile.email), ''),
    'Користувач ViCourt'
  )
  into actor_name
  from public.profiles profile
  where profile.id = auth.uid();

  actor_name := coalesce(actor_name, 'Користувач ViCourt');
  old_last_date := equipment_row.last_maintenance_date;
  old_next_date := equipment_row.next_service_date;
  old_current_usage := equipment_row.current_usage;
  old_last_usage := equipment_row.last_maintenance_usage;
  old_next_usage := equipment_row.next_maintenance_usage;

  if p_usage_reading is not null then
    usage_result := private.append_equipment_usage_log(
      equipment_row.id,
      p_usage_reading,
      today,
      'reading',
      'Показник зафіксовано під час планового ТО.',
      auth.uid(),
      actor_name,
      true
    );
    usage_log_id := (usage_result ->> 'usage_log_id')::bigint;

    select equipment.*
    into equipment_row
    from public.equipment equipment
    where equipment.id = p_equipment_id
    for update;
  end if;

  has_date_schedule :=
    equipment_row.maintenance_interval_days is not null
    and equipment_row.maintenance_interval_days > 0;
  has_usage_schedule :=
    equipment_row.usage_type in ('hours', 'km')
    and equipment_row.maintenance_interval_usage is not null
    and equipment_row.maintenance_interval_usage > 0;

  if not has_date_schedule and not has_usage_schedule then
    raise exception 'No maintenance interval is configured.'
      using errcode = '22023';
  end if;

  if has_usage_schedule and equipment_row.current_usage is null then
    raise exception 'Current usage is required to complete usage-based maintenance.'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.equipment_service_records records
    where records.equipment_id = equipment_row.id
      and records.service_type = 'Планове обслуговування'
      and records.service_date = today
      and records.voided_at is null
  ) then
    raise exception 'Maintenance was already completed today.'
      using errcode = '23505';
  end if;

  new_last_date := case when has_date_schedule then today else old_last_date end;
  new_next_date := case
    when has_date_schedule
      then today + equipment_row.maintenance_interval_days
    else old_next_date
  end;
  new_last_usage := case
    when has_usage_schedule then equipment_row.current_usage
    else old_last_usage
  end;
  new_next_usage := case
    when has_usage_schedule
      then equipment_row.current_usage + equipment_row.maintenance_interval_usage
    else old_next_usage
  end;

  update public.equipment
  set
    last_maintenance_date = new_last_date,
    next_service_date = new_next_date,
    last_maintenance_usage = new_last_usage,
    next_maintenance_usage = new_next_usage
  where id = equipment_row.id;

  if p_task_id is not null then
    select tasks.id
    into completed_task_id
    from public.object_tasks tasks
    where tasks.id = p_task_id
      and tasks.equipment_id = equipment_row.id
      and tasks.task_source = 'equipment_maintenance'
      and tasks.status <> 'Виконано'
    for update;

    if completed_task_id is null then
      raise exception 'Active equipment maintenance task was not found.'
        using errcode = 'P0002';
    end if;
  else
    select tasks.id
    into completed_task_id
    from public.object_tasks tasks
    where tasks.equipment_id = equipment_row.id
      and tasks.task_source = 'equipment_maintenance'
      and tasks.status <> 'Виконано'
    order by tasks.id
    limit 1
    for update;
  end if;

  if completed_task_id is not null then
    update public.object_tasks
    set status = 'Виконано'
    where id = completed_task_id;
  end if;

  insert into public.equipment_service_records (
    equipment_id,
    service_type,
    service_date,
    cost,
    performed_by,
    description,
    next_service_date,
    usage_reading,
    usage_type_snapshot,
    usage_log_id,
    created_by,
    created_by_name
  )
  values (
    equipment_row.id,
    'Планове обслуговування',
    today,
    p_cost,
    coalesce(nullif(btrim(p_performed_by), ''), actor_name),
    nullif(btrim(p_description), ''),
    new_next_date,
    case
      when has_usage_schedule or p_usage_reading is not null
        then equipment_row.current_usage
      else null
    end,
    case
      when has_usage_schedule or p_usage_reading is not null
        then equipment_row.usage_type
      else null
    end,
    usage_log_id,
    auth.uid(),
    actor_name
  )
  returning id into service_history_id;

  task_result := public.sync_equipment_maintenance_task(equipment_row.id);
  next_task_id := (task_result ->> 'task_id')::bigint;

  return jsonb_build_object(
    'service_history_id', service_history_id,
    'equipment_name', equipment_row.name,
    'previous_last_maintenance_date', old_last_date,
    'new_last_maintenance_date', new_last_date,
    'previous_next_service_date', old_next_date,
    'new_next_service_date', new_next_date,
    'maintenance_interval_days', equipment_row.maintenance_interval_days,
    'usage_type', equipment_row.usage_type,
    'previous_current_usage', old_current_usage,
    'new_current_usage', equipment_row.current_usage,
    'previous_last_maintenance_usage', old_last_usage,
    'new_last_maintenance_usage', new_last_usage,
    'previous_next_maintenance_usage', old_next_usage,
    'new_next_maintenance_usage', new_next_usage,
    'maintenance_interval_usage', equipment_row.maintenance_interval_usage,
    'usage_log_id', usage_log_id,
    'completed_task_id', completed_task_id,
    'next_task_id', next_task_id
  );
end
$function$;

