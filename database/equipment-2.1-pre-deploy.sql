    p_service_date,
    p_cost,
    nullif(btrim(p_performed_by), ''),
    nullif(btrim(p_description), ''),
    p_next_service_date,
    case when p_usage_reading is not null then equipment_row.current_usage else null end,
    case when p_usage_reading is not null then equipment_row.usage_type else null end,
    usage_log_id,
    auth.uid(),
    actor_name
  )
  returning id into service_history_id;

  if p_next_service_date is not null then
    update public.equipment
    set next_service_date = p_next_service_date
    where id = equipment_row.id;
  end if;

  task_result := public.sync_equipment_maintenance_task(equipment_row.id);

  return jsonb_build_object(
    'service_history_id', service_history_id,
    'equipment_id', equipment_row.id,
    'equipment_name', equipment_row.name,
    'service_type', p_service_type,
    'service_date', p_service_date,
    'cost', p_cost,
    'performed_by', nullif(btrim(p_performed_by), ''),
    'description', nullif(btrim(p_description), ''),
    'next_service_date', p_next_service_date,
    'usage_type', case when p_usage_reading is not null then equipment_row.usage_type else null end,
    'usage_reading', case when p_usage_reading is not null then equipment_row.current_usage else null end,
    'usage_log_id', usage_log_id,
    'task_sync', task_result
  );
end
