  select equipment.*
  into equipment_row
  from public.equipment equipment
  where equipment.id = p_equipment_id
  for update;

  if not found then
    raise exception 'Equipment was not found.'
      using errcode = 'P0002';
  end if;

  select coalesce(
    nullif(btrim(profile.full_name), ''),
    nullif(btrim(profile.email), ''),
    'Користувач ViCourt'
  )
  into actor_name
  from public.profiles profile
  where profile.id = auth.uid();

  actor_name := coalesce(actor_name, 'Користувач ViCourt');

  if p_usage_reading is not null then
    usage_result := private.append_equipment_usage_log(
      equipment_row.id,
      p_usage_reading,
      p_service_date,
      'reading',
      'Показник зафіксовано разом із сервісним записом.',
      auth.uid(),
      actor_name,
      true
    );
    usage_log_id := (usage_result ->> 'usage_log_id')::bigint;

    select equipment.*
    into equipment_row
    from public.equipment equipment
    where equipment.id = p_equipment_id
    for update;
  end if;

  insert into public.equipment_service_records (
    equipment_id,
    service_type,
    service_date,
    cost,
    performed_by,
    description,
    next_service_date,
    usage_reading,
    usage_type_snapshot,
