create or replace function public.void_equipment_service_record(
  p_service_record_id bigint,
  p_void_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  service_row public.equipment_service_records%rowtype;
  equipment_name text;
begin
  if auth.uid() is null
    or not private.is_active_user()
    or not private.is_admin()
  then
    raise exception 'Only an active administrator can void equipment service records.'
      using errcode = '42501';
  end if;

  if p_void_reason is null
    or char_length(btrim(p_void_reason)) not between 1 and 1000
  then
    raise exception 'A void reason is required.'
      using errcode = '22023';
  end if;

  select records.*
  into service_row
  from public.equipment_service_records records
  where records.id = p_service_record_id
  for update;

  if not found then
    raise exception 'Equipment service record was not found.'
      using errcode = 'P0002';
  end if;

  if service_row.voided_at is not null then
    raise exception 'Equipment service record is already voided.'
      using errcode = '22023';
  end if;

  select equipment.name
  into equipment_name
  from public.equipment equipment
  where equipment.id = service_row.equipment_id;

  update public.equipment_service_records
  set
    voided_at = clock_timestamp(),
    voided_by = auth.uid(),
    void_reason = btrim(p_void_reason)
  where id = service_row.id;

  return jsonb_build_object(
    'service_history_id', service_row.id,
    'equipment_id', service_row.equipment_id,
    'equipment_name', coalesce(equipment_name, 'Техніку видалено'),
    'service_type', service_row.service_type,
    'service_date', service_row.service_date,
    'cost', service_row.cost,
    'void_reason', btrim(p_void_reason)
  );
end
