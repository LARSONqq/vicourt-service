-- Internal helper. Public callers cannot execute it directly. It is shared by
-- usage entry, maintenance completion and manual service RPCs so their reading
-- semantics cannot drift.
create or replace function private.append_equipment_usage_log(
  p_equipment_id bigint,
  p_reading numeric,
  p_reading_date date,
  p_entry_type text,
  p_note text,
  p_actor_id uuid,
  p_actor_name text,
  p_skip_if_unchanged boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  equipment_row public.equipment%rowtype;
  previous_reading numeric(18,3);
  latest_reading_date date;
  usage_log_id bigint;
begin
  if p_reading is null
    or p_reading < 0
    or p_reading = 'NaN'::numeric
    or p_reading >= 'Infinity'::numeric
  then
    raise exception 'Usage reading must be a finite non-negative number.'
      using errcode = '22023';
  end if;

  if p_reading_date is null then
    raise exception 'Usage reading date is required.'
      using errcode = '22007';
  end if;

  if p_reading_date > (clock_timestamp() at time zone 'Europe/Kyiv')::date then
    raise exception 'Usage reading date cannot be in the future.'
      using errcode = '22007';
  end if;

  if p_entry_type not in ('reading', 'correction') then
    raise exception 'Unsupported usage entry type.'
      using errcode = '22023';
  end if;

  if p_note is not null and char_length(p_note) > 2000 then
    raise exception 'Usage note is too long.'
      using errcode = '22001';
  end if;

  select equipment.*
  into equipment_row
  from public.equipment equipment
  where equipment.id = p_equipment_id
  for update;

  if not found then
    raise exception 'Equipment was not found.'
      using errcode = 'P0002';
  end if;

  if equipment_row.usage_type not in ('hours', 'km') then
    raise exception 'Usage tracking is not configured for this equipment.'
      using errcode = '22023';
  end if;

  previous_reading := equipment_row.current_usage;

  select logs.reading_date
  into latest_reading_date
  from public.equipment_usage_logs logs
  where logs.equipment_id = equipment_row.id
  order by logs.reading_date desc, logs.id desc
  limit 1;

  if latest_reading_date is not null and p_reading_date < latest_reading_date then
    raise exception 'Usage readings must be entered in chronological order.'
      using errcode = '22007';
  end if;

  if previous_reading is not null and p_reading = previous_reading then
    if p_skip_if_unchanged then
      return jsonb_build_object(
        'equipment_id', equipment_row.id,
        'equipment_name', equipment_row.name,
        'usage_type', equipment_row.usage_type,
        'previous_current_usage', previous_reading,
        'new_current_usage', previous_reading,
        'reading_date', p_reading_date,
        'entry_type', p_entry_type,
        'usage_log_id', null,
        'appended', false
      );
    end if;

    raise exception 'The new usage reading is unchanged.'
      using errcode = '22023';
  end if;

  if p_entry_type = 'reading'
    and previous_reading is not null
    and p_reading < previous_reading
  then
    raise exception 'A normal usage reading cannot decrease.'
      using errcode = '22023';
  end if;

  insert into public.equipment_usage_logs (
    equipment_id,
    equipment_name_snapshot,
    inventory_number_snapshot,
    usage_type,
    reading,
    previous_reading,
    reading_date,
    entry_type,
    note,
    created_by,
    created_by_name
  )
  values (
    equipment_row.id,
    equipment_row.name,
    equipment_row.inventory_number,
    equipment_row.usage_type,
    p_reading,
    previous_reading,
    p_reading_date,
    p_entry_type,
    nullif(btrim(p_note), ''),
    p_actor_id,
    p_actor_name
  )
  returning id into usage_log_id;

  update public.equipment
  set current_usage = p_reading
  where id = equipment_row.id;

  return jsonb_build_object(
    'equipment_id', equipment_row.id,
    'equipment_name', equipment_row.name,
    'usage_type', equipment_row.usage_type,
    'previous_current_usage', previous_reading,
    'new_current_usage', p_reading,
    'reading_date', p_reading_date,
    'entry_type', p_entry_type,
    'usage_log_id', usage_log_id,
    'appended', true
  );
end
$function$;

